#!/usr/bin/env node
// tokens/type.json -> C++ header: fw::ty::Id (one per style, - -> _), the style table for both densities (#ifdef FW_1X),
// scales, number styles, and the Type page sections. Fonts come from tools/gen_fonts.py (same styles order).
// Run by build.sh: `node tools/gen_type.mjs <out.h>`; writes only when the output changes.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(HERE, '..', 'tokens', 'type.json'), 'utf8'));
const out = process.argv[2];
if (!out) { console.error('usage: gen_type.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/type.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');
const names = Object.keys(t.styles);
const scales = t.scales.map((s) => s.id);
for (const n of names) {
  const s = t.styles[n];
  if (!/^[a-z][a-z0-9-]*$/.test(n)) die(`bad style name "${n}"`);
  if (!scales.includes(s.scale)) die(`${n}: unknown scale "${s.scale}"`);
  if (!t.families[s.font]) die(`${n}: unknown font "${s.font}"`);
  if (!t.glyphsets[s.glyphs]) die(`${n}: unknown glyph set "${s.glyphs}"`);
  for (const k of ['weight', 'size', 'box']) if (!Number.isInteger(s[k]) || !Number.isInteger(s['1x']?.[k])) die(`${n}: ${k} (and 1x.${k}) must be integers`);
}
for (const x of t.numbers) {
  if (!t.styles[x.style]) die(`number ${x.id}: unknown style ${x.style}`);
  if (x.unitStyle && !t.styles[x.unitStyle]) die(`number ${x.id}: unknown unit style ${x.unitStyle}`);
}
const tab = new Set(t.tabular?.styles ?? []);
const L = [];
L.push('// GENERATED by tools/gen_type.mjs from tokens/type.json: edit the JSON, not this file.', '#pragma once', '', 'namespace fw {', 'namespace ty {');
L.push('// one id per type style (tokens/type.json styles order = the font table order in the generated font header)');
L.push(`enum Id { ${names.map(field).join(', ')}, N };`);
L.push('struct Style {', '  const char *name, *scale, *use, *sample, *glyphs;', '  bool mono, upper, tabular;', '  int weight, size, box;  // device px at this density', '  float line_height;', '  int letter_space;  // px', '};');
const row = (n, d) => {
  const s = t.styles[n], r = d === '1x' ? { ...s, ...s['1x'] } : s;
  return `  {${cstr(n)}, ${cstr(s.scale)}, ${cstr(s.use)}, ${cstr(s.sample)}, ${cstr(s.glyphs)}, ${s.font === 'mono'}, ${s.case === 'upper'}, ${tab.has(n)}, ${r.weight}, ${r.size}, ${r.box}, ${Number(r.lineHeight).toFixed(2)}f, ${r.letterSpacing}},`;
};
L.push('#ifdef FW_1X', 'constexpr Style STYLES[N] = {', ...names.map((n) => row(n, '1x')), '};', '#else', 'constexpr Style STYLES[N] = {', ...names.map((n) => row(n, '1.5x')), '};', '#endif');
L.push('struct Number { const char *id, *label, *sample, *unit, *unit_colour, *about; Id style; int unit_style; };  // unit_style -1 = inline');
L.push('constexpr Number NUMBERS[] = {');
for (const x of t.numbers) L.push(`  {${cstr(x.id)}, ${cstr(x.label)}, ${cstr(x.sample)}, ${cstr(x.unit === 'inline' ? '' : x.unit)}, ${cstr(x.unitColour ?? '')}, ${cstr(x.about)}, ${field(x.style)}, ${x.unitStyle ? field(x.unitStyle) : -1}},`);
L.push('};', `constexpr int N_NUMBERS = ${t.numbers.length};`);
L.push('struct Glyphset { const char *id, *about; };', 'constexpr Glyphset GLYPHSETS[] = {');
for (const [id, g] of Object.entries(t.glyphsets)) L.push(`  {${cstr(id)}, ${cstr(g.about)}},`);
L.push('};', `constexpr int N_GLYPHSETS = ${Object.keys(t.glyphsets).length};`);
L.push(`constexpr const char *TABULAR_ABOUT = ${cstr(t.tabular?.about)};`);
// Type page sections (foundations/type.cpp meta "variants")
const doc = [...t.scales.map((s) => ({ label: s.label, about: s.about, props: { section: s.id } })),
  { label: 'Mono caps and sans', about: 'Inter for words and numbers, JetBrains Mono for labels: mono labels are set in capitals (case: upper), sans never.', props: { section: 'pair' } },
  { label: 'Numbers', about: 'How numbers and their units are set. ' + (t.tabular?.about ?? ''), props: { section: 'numbers' } },
  { label: 'Glyph coverage', about: 'Every font of this build with the glyphs it carries (fonts carry only what their styles need: flash).', props: { section: 'glyphs' } },
  { label: 'Fonts in this build', about: 'One bitmap font per family, weight, size; flash = 4 bpp bitmaps + glyph table.', props: { section: 'fonts' } }];
L.push(`#define FW_TYPE_SECTIONS ${cstr(JSON.stringify(doc))}`);
L.push(`#define FW_TYPE_SECTION_IDS ${cstr(JSON.stringify(doc.map((d) => d.props.section)))}`);
L.push('}  // namespace ty', '}  // namespace fw', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen type_gen.h (${names.length} styles, ${t.numbers.length} number styles)`);
