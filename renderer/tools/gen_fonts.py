#!/usr/bin/env python3
"""tokens/type.json -> one C++ header of LVGL bitmap fonts for one density (README "Type tokens").

  usage: gen_fonts.py <1.5x|1x> <out.h>          (build.sh and firmware/bundle.mjs run it; rewrites only on change)

One font per (family, weight, size, tabular) that the styles of this density use, with only the glyphs those styles
need (union of their glyph sets, tokens/type.json "glyphsets"). Rasterised by ESPHome's own font code (FreeType,
4 bpp, same metrics as ESPHome's `font:`), so it needs a Python with the `esphome` package (FW_FONT_PY in local.env).
TTFs: `<FW_TTF>/<Family>@<weight>@False@v1.ttf` (ESPHome's Google Fonts cache naming; the files are SIL OFL).
Tabular styles (type.json "tabular"): digits 0-9 get one advance (the widest digit), glyph centred in it.
The header defines fw::gen::FacetFont F_<id> per font, STYLE_FONT[] (one per style, styles order) and FONTS[] (memory
report for the Type page).
"""
import functools
import hashlib
import json
import os
import sys
from itertools import accumulate
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "tokens" / "type.json"
den, out = sys.argv[1], Path(sys.argv[2])
TTF = Path(os.environ.get("FW_TTF", ""))
stamp = hashlib.sha1(SRC.read_bytes() + Path(__file__).read_bytes() + den.encode()).hexdigest()[:12]
if out.exists() and out.open().readline().strip().endswith(stamp):
    sys.exit(0)  # unchanged: skip the (slow) rasterising

from freetype import Face  # noqa: E402
from esphome.components.font import glyph_comparator, glyph_to_glyphinfo, pt_to_px  # noqa: E402
import esphome_glyphsets as glyphsets  # noqa: E402

t = json.loads(SRC.read_text())
tab = set(t.get("tabular", {}).get("styles", []))


def resolved(s: dict) -> dict:
    return {**s, **s.get("1x", {})} if den == "1x" else s


def chars(gs_id: str) -> set[str]:
    g = t["glyphsets"][gs_id]
    pts = {chr(x) for x in glyphsets.unicodes_per_glyphset(g["glyphset"])} if g.get("glyphset") else set()
    for c in g.get("chars", []):
        pts.update(c)
    return pts


fonts: dict[str, dict] = {}
style_font: list[str] = []
for name, s in t["styles"].items():
    r = resolved(s)
    fam = t["families"][r["font"]]["family"]
    fid = f"{r['font']}_{r['weight']}_{r['size']}{'t' if name in tab else ''}"
    f = fonts.setdefault(fid, {"family": fam, "mono": r["font"] == "mono", "weight": r["weight"], "size": r["size"],
                               "tabular": name in tab, "chars": set(), "styles": []})
    f["chars"] |= chars(r["glyphs"])
    f["styles"].append(name)
    style_font.append(fid)

H = [f"// GENERATED by tools/gen_fonts.py from tokens/type.json ({den}): edit the JSON, not this file. stamp {stamp}",
     "#pragma once", "#include <cstdint>", "#include <cstring>", '#include "lvgl.h"', "", "namespace fw {", "namespace gen {",
     (HERE / "facet_font.inc").read_text()]
faces: dict[str, Face] = {}
total = 0
report = []
for fid, f in fonts.items():
    path = TTF / f"{f['family']}@{f['weight']}@False@v1.ttf"
    if not path.exists():
        raise SystemExit(f"gen_fonts: {path} missing (set FW_TTF in local.env; fetch it from Google Fonts)")
    face = faces.setdefault(str(path), Face(str(path)))
    cps = sorted(f["chars"], key=functools.cmp_to_key(glyph_comparator))
    size, bpp = f["size"], 4
    infos = [glyph_to_glyphinfo(c, face, size, bpp) for c in cps]
    infos = [g for g in infos if g is not None]
    adv = {g.glyph: g.advance for g in infos}
    dmax = max((adv.get(ord(d), 0) for d in "0123456789"), default=0) if f["tabular"] else 0
    data = [b for g in infos for b in g.bitmap_data]
    nbytes = len(data) + 20 * len(infos)  # bitmaps + glyph table (flash; sizeof(FacetGlyph) = 20 on 32-bit)
    total += nbytes
    report.append((fid, f, len(infos), nbytes))
    H.append(f"// {fid}: {f['family']} {f['weight']} {size} px{' tabular' if f['tabular'] else ''}, {len(infos)} glyphs, "
             f"{nbytes} B; styles {', '.join(f['styles'])}")
    H.append(f"static const uint8_t {fid}_data[] = {{")
    for i in range(0, len(data), 32):
        H.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 32]) + ",")
    H.append("};")
    H.append(f"static const FacetGlyph {fid}_glyphs[] = {{")
    for g, end in zip(infos, accumulate(len(g.bitmap_data) for g in infos)):
        a, ox = g.advance, g.offset_x
        if dmax and chr(g.glyph) in "0123456789":
            ox += (dmax - a) // 2
            a = dmax
        H.append(f"  {{{g.glyph}, {fid}_data + {end - len(g.bitmap_data)}, {a}, {ox}, {g.offset_y}, {g.width}, {g.height}}},")
    H.append("};")
    H.append(f"inline FacetFont F_{fid}{{{fid}_glyphs, {len(infos)}, {pt_to_px(face.size.ascender)}, "
             f"{pt_to_px(face.size.height)}, {bpp}}};")
    H.append("")
H.append("// one font per style (tokens/type.json styles order)")
H.append(f"inline FacetFont *const STYLE_FONT[] = {{{', '.join('&F_' + x for x in style_font)}}};")
H.append("struct FontInfo { const char *id, *family; int weight, size; bool mono, tabular; int glyphs, bytes; FacetFont *f; };")
H.append("inline const FontInfo FONTS[] = {")
for fid, f, n, b in report:
    H.append(f'  {{"{fid}", "{f["family"]}", {f["weight"]}, {f["size"]}, {str(f["mono"]).lower()}, '
             f'{str(f["tabular"]).lower()}, {n}, {b}, &F_{fid}}},')
H += ["};", f"constexpr int N_FONTS = {len(report)};", f"constexpr int FONT_BYTES = {total};",
      "}  // namespace gen", "}  // namespace fw", ""]
tmp = out.with_suffix(f".{os.getpid()}")
tmp.write_text("\n".join(H))
tmp.replace(out)
print(f"gen {out.name} ({den}: {len(report)} fonts, {total // 1024} KB)")
