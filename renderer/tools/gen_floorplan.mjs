#!/usr/bin/env node
// tokens/floorplan.json -> C++ header floorplan_gen.h: fw::fp:: the Floor plans foundation (geometry in metres, the
// inks as colour.json Theme fields, opacities, strokes, the robot's glide, the rules in plain words for the page).
// Run by build.sh: `node tools/gen_floorplan.mjs <out.h>`; writes only when the output changes.
// Fails on unknown colour / stroke tokens, a missing about, or geometry that isn't a positive number.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const rd = (f) => JSON.parse(readFileSync(join(HERE, '..', 'tokens', f), 'utf8'));
const t = rd('floorplan.json'), col = rd('colour.json'), spc = rd('space.json');
const out = process.argv[2];
if (!out) { console.error('usage: gen_floorplan.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/floorplan.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');
const colour = (n) => { if (!col.colours[n]) die(`unknown colour token ${n}`); return `&Theme::${field(n)}`; };
const stroke = (n) => { if (!spc.tokens?.stroke?.[n]) die(`unknown stroke ${n}`); return `stroke::${field(n)}`; };
if (!t.about) die('about missing');
const L = ['// generated by tools/gen_floorplan.mjs from tokens/floorplan.json: do not edit', '#pragma once', '#include "colour_gen.h"', 'namespace fw::fp {', 'using Ink = lv_color_t Theme::*;'];
L.push('// geometry (metres)');
for (const k of ['slab', 'wall', 'robot-r', 'robot-h', 'lidar', 'robot-real-r']) { if (!(t.geometry[k] > 0)) die(`geometry.${k} must be > 0`); L.push(`constexpr float ${field(k).toUpperCase()} = ${t.geometry[k]}f;`); }
L.push('// inks (colour tokens)');
for (const [k, v] of Object.entries(t.ink)) L.push(`constexpr Ink INK_${field(k).toUpperCase()} = ${colour(v)};  // ${v}`);
L.push('// opacities (percent, mixed when the image is drawn)');
for (const [k, v] of Object.entries(t.opacity)) { if (k === 'about') continue; if (!(v > 0 && v <= 100)) die(`opacity.${k} 1..100`); L.push(`constexpr int OPA_${field(k).toUpperCase()} = ${v};`); }
L.push('// strokes (device px)');
for (const [k, v] of Object.entries(t.stroke)) L.push(`constexpr int W_${field(k).toUpperCase()} = ${stroke(v)};`);
L.push('// the generator (core/floorplan_auto.cpp): metres, % as noted', 'namespace gen {');
for (const [k, v] of Object.entries(t.generate || {})) { if (k === 'about') continue; if (!(v > 0)) die(`generate.${k} must be > 0`); L.push(`constexpr float ${field(k).toUpperCase()} = ${Number.isInteger(v) ? v + ".0" : v}f;`); }
L.push('}  // namespace gen');
if (!(t.motion?.['glide-ms'] > 0)) die('motion.glide-ms');
L.push(`constexpr uint32_t GLIDE_MS = ${t.motion['glide-ms']};`);
if (!(t.rules?.length)) die('rules missing');
L.push('struct Rule { const char *id, *title, *about; };', `constexpr int N_RULES = ${t.rules.length};`, 'constexpr Rule RULES[N_RULES] = {');
for (const r of t.rules) { if (!r.about || !r.title) die(`rules.${r.id}: title + about`); L.push(`  {${cstr(r.id)}, ${cstr(r.title)}, ${cstr(r.about)}},`); }
L.push('};', '}  // namespace fw::fp', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen floorplan_gen.h (${Object.keys(t.ink).length} inks, ${t.rules.length} rules)`);
