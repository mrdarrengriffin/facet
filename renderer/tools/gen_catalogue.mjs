#!/usr/bin/env node
// The spec catalogue (core/spec.h catalogue(): one source) -> catalogue/catalogue.json (components, props, which events
// take which actions, binds, budgets, a cost per component: objects in its default build) + catalogue/spec.schema.json
// (JSON Schema for a screen spec and a deck: the editor, later). Runs on the WASM build (1.5x). Writes only on change.
// Usage: node tools/gen_catalogue.mjs [--build <dir with 1.5x/>]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const env = (() => { try { return Object.fromEntries(readFileSync(join(HERE, '..', 'local.env'), 'utf8').split('\n').map((l) => l.match(/^([A-Z_]+)=(.*)$/)).filter(Boolean).map((m) => [m[1], m[2]])); } catch { return {}; } })();
const i = process.argv.indexOf('--build');
const BUILD = i > 0 ? process.argv[i + 1] : process.env.FW_OUT || env.FW_OUT || join(HERE, 'out');
const F = (await import(pathToFileURL(join(BUILD, '1.5x', 'fw.mjs')).href)).default;
const m = await F();
m._fw_init();
m._fw_stage(720, 720);
const cat = JSON.parse(m.UTF8ToString(m._fw_catalogue()));
const bind = { type: 'object', additionalProperties: false, required: ['e'], properties: { e: { type: 'string', pattern: '^(\\$[a-z_]+|[a-z_]+\\.[a-z0-9_]+)$' }, a: { type: 'string' }, fmt: { enum: cat.fmt } } };
const param = { type: 'string', pattern: '^\\$' };
const node = (id, c) => ({
  type: 'object', additionalProperties: false, required: ['c'],
  properties: {
    c: { const: id },
    p: { type: 'object', additionalProperties: false, properties: Object.fromEntries(c.props.map((p) => [p.name, { anyOf: [
      p.type === 'bool' ? { type: 'boolean' } : p.type === 'range' ? { type: 'number', minimum: p.min, maximum: p.max } : p.options ? { enum: p.options } : { type: 'string', maxLength: 64 },
      { $ref: '#/$defs/bind' }, { $ref: '#/$defs/param' }] }])) },
    on: { type: 'object', additionalProperties: false, properties: Object.fromEntries(Object.entries(c.events).map(([ev, acts]) => [ev, { $ref: '#/$defs/action', properties: { do: { enum: acts } } }])) },
    pending: { type: 'object', additionalProperties: { type: 'array', items: { type: 'string' }, minItems: 2, maxItems: 2 } },
  },
});
const schema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema', $id: 'facet/spec.schema.json', title: 'Facet screen spec or deck',
  description: `Generated by tools/gen_catalogue.mjs from core/spec.h (catalogue ${cat.hash}). Not validated here: core/spec.h is the validator.`,
  oneOf: [{ $ref: '#/$defs/screen' }, { $ref: '#/$defs/deck' }],
  $defs: {
    bind, param,
    action: { type: 'object', additionalProperties: false, required: ['do'], properties: { do: { enum: cat.actions }, e: { type: 'string' }, screen: { type: 'string', pattern: '^[a-z0-9_]{1,12}$' }, params: { type: 'object', additionalProperties: { type: 'string' } } } },
    screen: { type: 'object', additionalProperties: false, required: ['v', 'id', 'rev', 'layout', 'nodes'], properties: {
      v: { const: cat.protocol }, id: { type: 'string', pattern: '^[a-z0-9_]{1,12}$' }, name: { type: 'string' }, rev: { type: 'integer', minimum: 0 },
      params: { type: 'object', additionalProperties: { type: 'string' } }, header: { type: 'object', additionalProperties: false, properties: { label: { type: 'string' }, back: { type: 'boolean' } } },
      layout: { enum: cat.layouts }, nodes: { type: 'array', maxItems: cat.budget.nodes, items: { oneOf: Object.keys(cat.components).map((id) => ({ $ref: `#/$defs/c_${id}` })) } } } },
    ...Object.fromEntries(Object.entries(cat.components).map(([id, c]) => [`c_${id}`, node(id, c)])),
    deck: { type: 'object', additionalProperties: false, required: ['v', 'rev', 'screens'], properties: { v: { const: cat.protocol }, rev: { type: 'integer' },
      screens: { type: 'array', minItems: 1, maxItems: cat.budget.screens, items: { type: 'object', additionalProperties: false, required: ['id'], properties: { id: { type: 'string' }, card: { type: 'boolean' } } } } } },
  },
};
const D = join(HERE, 'catalogue');
mkdirSync(D, { recursive: true });
const put = (f, o) => { const s = JSON.stringify(o, null, 1) + '\n'; if (!existsSync(join(D, f)) || readFileSync(join(D, f), 'utf8') !== s) writeFileSync(join(D, f), s); };
put('catalogue.json', cat);
put('spec.schema.json', schema);
console.log(`catalogue ${cat.hash}: ${Object.keys(cat.components).length} components, ${Object.values(cat.components).filter((c) => Object.keys(c.events).length).length} with actions`);
