#!/usr/bin/env node
// specs/*.json (the factory screens) + specs/deck.json + sources/sources.json -> specs_gen.h (fw::spec::FACTORY,
// FACTORY_DECK, SOURCES): compiled into
// the firmware and the WASM build, so a panel works with no hub (core/spec.h). Minified; checked here for JSON only
// (the full validation is core/spec.h's, run by tools/spec.mjs and on the panel). Writes only when the output changes.
// Feature flags (tools/features.mjs): a FW_FEATURES=docs|firmware build leaves out the specs of hidden features and
// their deck pages + Home cards (factory deck, Home, Settings > Screens follow from these lists).
// Usage: node gen_specs.mjs <out.h>
import { flavour, hiddenIds, hiddenCards, load as loadFeatures } from './features.mjs';
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const D = join(HERE, '..', 'specs');
const out = process.argv[2];
if (!out) { console.error('usage: gen_specs.mjs <out.h>'); process.exit(1); }
const fail = (m) => { console.error(`gen_specs: ${m}`); process.exit(1); };
const files = readdirSync(D).filter((f) => f.endsWith('.json')).sort();
// FW_SPECS_OVERLAY = a directory of a house's own specs (deck.json, <id>.json): a file there replaces the factory spec of
// the same name in this build (a house's own panels bake in their real entities; the repo's specs use demo ids)
const OV = process.env.FW_SPECS_OVERLAY || '';
const read = (f) => { const p = OV && existsSync(join(OV, f)) ? join(OV, f) : join(D, f); try { return JSON.parse(readFileSync(p, 'utf8')); } catch (e) { fail(`${f}: ${e.message}`); } };
const raw = (s) => { const j = JSON.stringify(s); if (j.includes(')FW"')) fail('a spec contains )FW"'); return `R"FW(${j})FW"`; };
const L = ['// GENERATED by tools/gen_specs.mjs from renderer/specs/*.json: edit the JSON, not this file.', '#pragma once', 'namespace fw {', 'namespace spec {',
  'struct FactorySpec { const char *id, *json; };', 'constexpr FactorySpec FACTORY[] = {'];
let deck = null;
const FLAV = flavour(), FL = loadFeatures(), HIDE = hiddenIds(FLAV, FL), HIDE_CARDS = hiddenCards(FLAV, FL);
for (const f of files) {
  const s = read(f), id = basename(f, '.json');
  if (id === 'deck') { deck = s; continue; }
  if (s.id !== id) fail(`${f}: id ${s.id} != file name`);
  if (HIDE.has(id)) continue;
  // a parameter's "about" is for the docs, the agent guide and the editor: the panel never shows it, so it stays out of the firmware
  for (const v of Object.values(s.params ?? {})) if (v && typeof v === 'object') delete v.about;
  L.push(`    {${JSON.stringify(id)}, ${raw(s)}},`);
}
if (!deck) fail('no specs/deck.json');
if (FLAV) {  // hidden pages out of the factory deck, and the Home cards that open them
  deck.pages = deck.pages.filter((p) => !HIDE.has(p.kind));
  const ids = new Set(deck.pages.map((p) => p.id));
  for (const p of deck.pages) if (p.cards) p.cards = p.cards.filter((c) => !HIDE_CARDS.has(c.t) && (!c.page || ids.has(c.page)));
  for (const p of deck.pages) {  // a header shortcut to a hidden page falls back to Settings
    const b = p.header_actions?.button;
    if (b && b !== 'settings' && !ids.has(b)) delete p.header_actions.button;
  }
  if (!ids.has(deck.start)) deck.start = deck.pages[0]?.id;
}
// the source catalogue (renderer/sources/sources.json): Settings > Screens lists a screen's sources from it
let sources;
try { sources = JSON.parse(readFileSync(join(HERE, '..', 'sources', 'sources.json'), 'utf8')); } catch (e) { fail(`sources.json: ${e.message}`); }
delete sources.$comment;
for (const [id, sc] of Object.entries(sources.screens ?? {}))
  for (const x of sc.sources ?? []) if (!/^[a-z0-9_]{1,24}$/.test(x.id) || !sources.kinds[x.kind]) fail(`sources.json ${id}: bad source ${x.id} / ${x.kind}`);
L.push('};', `constexpr const char *FACTORY_DECK = ${raw(deck)};`, `constexpr const char *SOURCES = ${raw(sources)};`, '}  // namespace spec', '}  // namespace fw', '');
const text = L.join('\n');
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text);
