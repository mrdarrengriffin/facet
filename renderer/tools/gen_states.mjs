#!/usr/bin/env node
// tokens/states.json -> C++ header: fw::st:: the interaction state rules every component reads (README "State tokens"):
// the LVGL state bits (OFF = disabled + unavailable), the Motion patterns of pressing and switching, a colour role
// function per state x role (e.g. fw::st::disabled_ink(t) = t.text_mute; pressed_tint(t) = the press-tint mix), the
// Card press style, the event / sound names (blocked + error, toggle-on / off), the unavailable words, the focus ring
// (stroke + offset from space.json) and small helpers (blocked(), press_transitions(); the ring = fw::focus_ring in core/atoms.h); plus the tables
// of the States foundation page. states.json names tokens only: every reference is checked against colour.json
// (colours + mixes), motion.json (patterns), sound.json (types) and space.json, and the build fails on a bad one.
// Run by build.sh / firmware/bundle.mjs: `node tools/gen_states.mjs <out.h>`; writes only when the output changes.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(readFileSync(join(HERE, '..', 'tokens', f), 'utf8'));
const t = read('states.json'), colour = read('colour.json'), motion = read('motion.json'), sound = read('sound.json'), space = read('space.json');
const out = process.argv[2];
if (!out) { console.error('usage: gen_states.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/states.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');

const colours = new Set(Object.keys(colour.colours)), mixes = Object.keys(colour.mixes ?? {});
const patterns = new Set(Object.keys(motion.patterns)), sounds = new Set(sound.types.map((x) => x.id));
const checkSound = (where, s) => { if (s && !sounds.has(s)) die(`${where}: unknown sound "${s}" (sound.json types)`); };
const spaceRef = (where, ref) => {
  const [g, k] = String(ref).split('.');
  if (!space.tokens?.[g]?.[k]) die(`${where}: unknown space token "${ref}" (space.json tokens.<group>.<name>)`);
  return `${g}::${field(k)}`;
};

const LVGL = { pressed: 'LV_STATE_PRESSED', on: 'LV_STATE_CHECKED', off: 'LV_STATE_USER_1' };
for (const [k, v] of Object.entries(LVGL)) if (t.lvgl?.[k]?.state !== v) die(`lvgl.${k}.state must be ${v} (the components rely on it)`);

const S = Object.entries(t.states);
const roles = [];
for (const [id, s] of S) {
  if (!s.label || !s.about) die(`states.${id}: label and about`);
  for (const m of s.motion ?? []) if (!patterns.has(m)) die(`states.${id}.motion: unknown pattern "${m}" (motion.json)`);
  checkSound(`states.${id}.sound`, s.sound);
  checkSound(`states.${id}.off_sound`, s.off_sound);
  for (const [k, x] of Object.entries(s.sounds ?? {})) checkSound(`states.${id}.sounds.${k}`, x.sound);
  for (const [r, x] of Object.entries(s.roles ?? {})) {
    if (x.token && !colours.has(x.token)) die(`states.${id}.roles.${r}: unknown colour "${x.token}" (colour.json colours)`);
    if (x.mix && !mixes.includes(x.mix)) die(`states.${id}.roles.${r}: unknown mix "${x.mix}" (colour.json mixes)`);
    if (!x.token === !x.mix) die(`states.${id}.roles.${r}: exactly one of token / mix`);
    roles.push({ state: id, role: r, fn: `${field(id)}_${field(r)}`, ...x });
  }
}
const st = (id) => t.states[id] ?? die(`states.${id} missing`);
const press = st('pressed'), dis = st('disabled'), un = st('unavailable'), on = st('on'), focus = st('focus'), rest = st('rest');
if (!press.style?.options?.includes(press.style.value)) die('states.pressed.style: value not one of its options');
const [pIn, pOut] = press.motion;
const [sw, sweep] = on.motion;
const ringW = spaceRef('states.focus.ring.width', focus.ring?.width), ringO = spaceRef('states.focus.ring.offset', focus.ring?.offset);
const ringC = focus.roles?.ring?.token ?? die('states.focus.roles.ring');

const L = ['// GENERATED by tools/gen_states.mjs from tokens/states.json: edit the JSON, not this file.', '#pragma once', '', 'namespace fw {', 'namespace st {'];
L.push('// LVGL state bits (states.json lvgl): OFF = disabled and unavailable (USER_1: events still arrive, outranks PRESSED)');
L.push('constexpr lv_state_t PRESSED = LV_STATE_PRESSED, ON = LV_STATE_CHECKED, OFF = LV_STATE_USER_1;');
L.push('// Motion: pressing (colour in / out), switching (knob) and sweeping (a value)');
L.push(`constexpr mo::Id PRESS_IN = mo::${field(pIn)}, PRESS_OUT = mo::${field(pOut)}, SWITCH = mo::${field(sw)}, SWEEP = mo::${field(sweep)};`);
L.push('// colour roles: <state>_<role>(theme)');
for (const r of roles) {
  if (r.token) L.push(`inline lv_color_t ${r.fn}(const Theme &t) { return t.${field(r.token)}; }  // ${r.token}`);
  else L.push(`inline lv_color_t ${r.fn}(const Theme &t) {  // mix ${r.mix}`, `  static int k = -1;`, `  if (k < 0) for (int i = 0; i < tokens::N_MIXES; i++) if (!strcmp(tokens::MIXES[i].name, ${cstr(r.mix)})) k = i;`, `  return k < 0 ? t.surface : tokens::mix(tokens::MIXES[k], t);`, '}');
}
L.push(`constexpr const char *PRESS_STYLE = ${cstr(press.style.value)};  // Card: ${press.style.options.join(' | ')}`);
L.push('// events and sounds');
L.push(`constexpr const char *TAP_EVENT = ${cstr(rest.event)}, *TAP_SOUND = ${cstr(rest.sound)};`);
L.push(`constexpr const char *BLOCKED_EVENT = ${cstr(dis.event)}, *BLOCKED_SOUND = ${cstr(dis.sound)};`);
L.push(`constexpr const char *SWITCH_EVENT = ${cstr(on.event)}, *ON_SOUND = ${cstr(on.sound)}, *OFF_SOUND = ${cstr(on.off_sound)};`);
L.push(`constexpr const char *UNAVAILABLE_TEXT = ${cstr(un.text)}, *PLACEHOLDER = ${cstr(un.placeholder)};`);
if (dis.moment !== 'press' && dis.moment !== 'release') die('states.disabled.moment: press | release');
L.push(`constexpr bool BLOCKED_ON_PRESS = ${dis.moment === 'press'};  // a blocked tap answers on finger down`);
L.push('// a tap handler registered for both PRESSED and CLICKED (on_tap) runs only at the right moment: blocked on press, a real tap on CLICKED');
L.push('inline bool tap_now(lv_event_t *e) {', '  const bool off = lv_obj_has_state((lv_obj_t *) lv_event_get_current_target(e), OFF);', '  return lv_event_get_code(e) == (off && BLOCKED_ON_PRESS ? LV_EVENT_PRESSED : LV_EVENT_CLICKED);', '}');
L.push('inline void on_tap(lv_obj_t *o, lv_event_cb_t cb, void *user) {', '  lv_obj_add_event_cb(o, cb, LV_EVENT_PRESSED, user);', '  lv_obj_add_event_cb(o, cb, LV_EVENT_CLICKED, user);', '}');
L.push('// focus ring (space.json): width, offset outside the box');
L.push(`constexpr int FOCUS_W = ${ringW}, FOCUS_OFFSET = ${ringO};`);
L.push('// a blocked tap: the event + error (disabled and unavailable)');
L.push('inline void blocked(lv_obj_t *o, const char *detail) { emit(o, BLOCKED_EVENT, detail); sound(o, BLOCKED_SOUND); }');
L.push('// the press fades on `props`: d[0] = release (resting looks), d[1] = press (pressed looks); LVGL runs the transition of the state entered');
L.push('inline void press_transitions(lv_style_transition_dsc_t d[2], const lv_style_prop_t *props) {');
L.push('  mo::transition(&d[0], PRESS_OUT, props);', '  mo::transition(&d[1], PRESS_IN, props);', '}');
// the focus ring itself = core atom fw::focus_ring (core/atoms.h, its own page components/focus_ring.cpp)

// the States page tables
L.push('// ---- States foundation page tables');
L.push('struct State { const char *id, *label, *about, *motion, *event, *sound; };', 'constexpr State STATES[] = {');
for (const [id, s] of S) L.push(`  {${cstr(id)}, ${cstr(s.label)}, ${cstr(s.about)}, ${cstr((s.motion ?? []).join(' / '))}, ${cstr(s.event)}, ${cstr([s.sound, s.off_sound].filter(Boolean).join(' / '))}},`);
L.push('};', `constexpr int N_STATES = ${S.length};`);
L.push('struct Role { const char *state, *role, *token, *use; bool mix; lv_color_t (*colour)(const Theme &); };', 'constexpr Role ROLES[] = {');
for (const r of roles) L.push(`  {${cstr(r.state)}, ${cstr(r.role)}, ${cstr(r.token ?? r.mix)}, ${cstr(r.use)}, ${r.mix ? 'true' : 'false'}, ${r.fn}},`);
L.push('};', `constexpr int N_ROLES = ${roles.length};`);
const snd = Object.entries(rest.sounds ?? {});
L.push('struct TapSound { const char *id, *sound, *use; };', 'constexpr TapSound TAP_SOUNDS[] = {');
for (const [k, x] of snd) L.push(`  {${cstr(k)}, ${cstr(x.sound)}, ${cstr(x.use)}},`);
L.push('};', `constexpr int N_TAP_SOUNDS = ${snd.length};`);
L.push('constexpr const char *RULES[] = {', ...t.rules.map((r) => `  ${cstr(r)},`), '};', `constexpr int N_RULES = ${t.rules.length};`);
const cols = t.audit.columns;
L.push(`constexpr const char *AUDIT_COLS[] = {${cols.map(cstr).join(', ')}};`, `constexpr int N_AUDIT_COLS = ${cols.length};`);
L.push(`struct AuditRow { const char *component; const char *cells[${cols.length}]; };`, 'constexpr AuditRow AUDIT[] = {');
for (const r of t.audit.rows) {
  for (const c of cols) if (r[c] === undefined) die(`audit ${r.c}: missing ${c}`);
  L.push(`  {${cstr(r.c)}, {${cols.map((c) => cstr(r[c])).join(', ')}}},`);
}
L.push('};', `constexpr int N_AUDIT = ${t.audit.rows.length};`);
L.push('struct Decision { const char *q, *decision; };', 'constexpr Decision DECISIONS[] = {');
for (const q of t.decisions.items) { if (!q.q || !q.decision) die('decisions: q + decision'); L.push(`  {${cstr(q.q)}, ${cstr(q.decision)}},`); }
L.push('};', `constexpr int N_DECISIONS = ${t.decisions.items.length};`);
L.push('}  // namespace st');
const sec = (id, label, about) => ({ label, about, props: { section: id } });
const doc = [
  sec('rules', 'Rules', `${t.about} The rules in plain words; every look below is the real component, built by its own code.`),
  sec('pressed', press.label, press.about),
  sec('disabled', dis.label, dis.about),
  sec('unavailable', un.label, un.about),
  sec('on', on.label, on.about),
  sec('focus', focus.label, focus.about),
  sec('tap', rest.label, rest.about),
  sec('audit', 'Audit', 'What each approved component did per state before the states were written down (round 1). The page and the components now read these rules from tokens/states.json.'),
  sec('decisions', 'Decisions', 'The inconsistencies the audit found, each decided by Darren (2026-10-21: "I think your suggestions are great here") and now a rule above.'),
];
L.push(`#define FW_STATES_SECTIONS ${cstr(JSON.stringify(doc))}`);
L.push(`#define FW_STATES_SECTION_IDS ${cstr(JSON.stringify(doc.map((d) => d.props.section)))}`);
L.push('}  // namespace fw', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen states_gen.h (${S.length} states, ${roles.length} roles)`);
