#!/usr/bin/env node
// tokens/colour.json -> C++ header (fw::Theme fields + token tables + accent sets + contrast pairs + the JSON itself
// for the page). Run by build.sh: `node tools/gen_colour.mjs <out.h>`; writes only when the output changes.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pairs as contrastPairs, mixOpa } from './contrast.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, '..', 'tokens', 'colour.json');
const out = process.argv[2];
if (!out) { console.error('usage: gen_colour.mjs <out.h>'); process.exit(2); }
const t = JSON.parse(readFileSync(SRC, 'utf8'));
const die = (m) => { console.error(`tokens/colour.json: ${m}`); process.exit(1); };
const HEX = /^#[0-9A-Fa-f]{6}$/;
const field = (n) => n.replace(/-/g, '_');
const hex = (v, where) => { if (!HEX.test(v)) die(`${where}: "${v}" is not #RRGGBB`); return `0x${v.slice(1).toUpperCase()}`; };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const names = Object.keys(t.colours);
const groups = t.groups.map((g) => g.id);
for (const n of names) {
  if (!/^[a-z][a-z0-9-]*$/.test(n)) die(`bad token name "${n}"`);
  if (!groups.includes(t.colours[n].group)) die(`${n}: unknown group "${t.colours[n].group}"`);
}
const a = t.accent, roles = a.roles;
for (const r of roles) if (!names.includes(r)) die(`accent role ${r} is not a colour token`);
if (!a.sets.some((s) => s.id === a.default)) die(`accent default "${a.default}" is not a set`);
let CP; try { CP = contrastPairs(t); } catch (e) { die(e.message); }
const kinds = Object.keys(t.contrast.kinds), sections = [...new Set(CP.map((p) => p.section))];

const L = [];
L.push('// GENERATED by tools/gen_colour.mjs from tokens/colour.json: edit the JSON, not this file.', '#pragma once', '#include <cstddef>', '#include <cstdint>', '#include "lvgl.h"', '', 'namespace fw {');
L.push('// one theme = every colour token resolved for dark or light + the selected accent set', 'struct Theme {', '  bool light;', '  int accent_set;  // index into tokens::ACCENTS');
for (let i = 0; i < names.length; i += 8) L.push(`  lv_color_t ${names.slice(i, i + 8).map(field).join(', ')};`);
L.push('};', '', 'namespace tokens {');
L.push('struct Group { const char *id, *label, *about; };', `constexpr Group GROUPS[] = {`);
for (const g of t.groups) L.push(`  {${cstr(g.id)}, ${cstr(g.label)}, ${cstr(g.about)}},`);
L.push('};', `constexpr int N_GROUPS = ${t.groups.length};`, '');
L.push('struct Colour { const char *name, *group, *role; uint32_t dark, light; size_t off; };', 'constexpr Colour COLOURS[] = {');
for (const n of names) { const c = t.colours[n]; L.push(`  {${cstr(n)}, ${cstr(c.group)}, ${cstr(c.role)}, ${hex(c.dark, n)}, ${hex(c.light, n)}, offsetof(Theme, ${field(n)})},`); }
L.push('};', `constexpr int N_COLOURS = ${names.length};`, '');
L.push(`constexpr int N_ROLES = ${roles.length};`, `constexpr const char *ROLES[N_ROLES] = {${roles.map(cstr).join(', ')}};`);
L.push(`constexpr size_t ROLE_OFF[N_ROLES] = {${roles.map((r) => `offsetof(Theme, ${field(r)})`).join(', ')}};`);
L.push('struct Accent { const char *id, *label; uint32_t dark[N_ROLES], light[N_ROLES]; };', 'constexpr Accent ACCENTS[] = {');
for (const s of a.sets) {
  const v = (th) => roles.map((r) => hex(s[th]?.[r] ?? die(`accent ${s.id} ${th}: no ${r}`), `accent ${s.id} ${th} ${r}`)).join(', ');
  L.push(`  {${cstr(s.id)}, ${cstr(s.label)}, {${v('dark')}}, {${v('light')}}},`);
}
L.push('};', `constexpr int N_ACCENTS = ${a.sets.length};`, `constexpr int ACCENT_DEFAULT = ${a.sets.findIndex((s) => s.id === a.default)};`, '');
// contrast pairs (tools/contrast.mjs pairs(): one entry per declared pair x background); kind = index into KINDS
L.push('struct Kind { const char *id, *label, *about; float min; };', 'constexpr Kind KINDS[] = {');
for (const k of kinds) { const v = t.contrast.kinds[k]; L.push(`  {${cstr(k)}, ${cstr(v.label)}, ${cstr(v.about)}, ${Number(v.min).toFixed(2)}f},`); }
L.push('};', `constexpr int N_KINDS = ${kinds.length};`);
L.push('struct Pair { const char *section, *fg, *bg, *use; int kind; float min; };', 'constexpr Pair CONTRAST[] = {');
for (const p of CP) L.push(`  {${cstr(p.section)}, ${cstr(p.fg)}, ${cstr(p.bg)}, ${cstr(p.use)}, ${kinds.indexOf(p.kind)}, ${Number(p.min).toFixed(2)}f},`);
L.push('};', `constexpr int N_CONTRAST = ${CP.length};`, '');
// component tokens (colour.json "components": {<component>: {<key>: {value, options, use}}}) -> fw::tokens::comp::<component>_<key>
L.push('// component tokens (a theme may set them later): a string value from its options', 'namespace comp {');
for (const [c, keys] of Object.entries(t.components ?? {}))
  for (const [k, v] of Object.entries(keys)) {
    if (v.options && !v.options.includes(v.value)) die(`components.${c}.${k}: "${v.value}" is not one of its options`);
    const use = String(v.use ?? '').replace(/\n/g, ' ');
    if (typeof v.value === 'number') L.push(`constexpr float ${field(c)}_${field(k)} = ${v.value}f;  // ${use}`);
    else L.push(`constexpr const char *${field(c)}_${field(k)} = ${cstr(v.value)};  // ${use}`);
  }
L.push('}  // namespace comp', '');
// mixes (colour.json "mixes"): tint over a base token at a component token's opacity, = lv_color_mix(tint, over, opa)
L.push('// mix tokens: fw::tokens::mix(MIXES[i], theme) = lv_color_mix(tint, over, opa); contrast pairs may name them', 'struct Mix { const char *name, *tint, *over, *toward, *use; size_t tint_off, over_off, toward_off; uint8_t opa, desat; };  // toward = "" -> no desaturation', 'constexpr Mix MIXES[] = {');
const mixes = Object.entries(t.mixes ?? {});
for (const [n, m] of mixes) {
  if (names.includes(n)) die(`mix ${n} clashes with a colour token`);
  for (const k of [m.tint, m.over, ...(m.toward ? [m.toward] : [])]) if (!names.includes(k)) die(`mix ${n}: unknown token ${k}`);
  let o, d = 0; try { o = mixOpa(t, m); if (m.toward) d = mixOpa(t, m, 'desat'); } catch (e) { die(e.message); }
  const tw = m.toward ?? m.tint;
  L.push(`  {${cstr(n)}, ${cstr(m.tint)}, ${cstr(m.over)}, ${cstr(m.toward ?? '')}, ${cstr(m.use)}, offsetof(Theme, ${field(m.tint)}), offsetof(Theme, ${field(m.over)}), offsetof(Theme, ${field(tw)}), ${o}, ${d}},`);
}
if (!mixes.length) L.push('  {"", "", "", "", "", 0, 0, 0, 0, 0},');
L.push('};', `constexpr int N_MIXES = ${mixes.length};`);
L.push('inline lv_color_t mix(const Mix &m, const Theme &t) {', '  auto at = [&](size_t off) { return *(const lv_color_t *) ((const char *) &t + off); };', '  const lv_color_t tint = m.toward[0] ? lv_color_mix(at(m.toward_off), at(m.tint_off), m.desat) : at(m.tint_off);', '  return lv_color_mix(tint, at(m.over_off), m.opa);', '}', '');
L.push('// accent set ids as a JSON array literal, for component meta: R"(...)" FW_ACCENT_IDS R"(...)"');
L.push(`#define FW_ACCENT_IDS ${cstr(JSON.stringify(a.sets.map((s) => s.id)))}`);
L.push('// the Colour page sections (foundations/colour.cpp meta "variants"): one per group, then accent sets, contrast');
const doc = [...t.groups.map((g) => ({ label: g.label, about: g.about, props: { group: g.id } })),
  { label: 'Accent sets', about: a.about, props: { group: 'accents' } },
  { label: 'Contrast: summary', about: `${t.contrast.about} Every theme x accent set: combinations that pass / tested; a cross = something fails (the next section lists it).`, props: { group: 'contrast' } },
  { label: 'Contrast: failures', about: 'Every failing combination across all themes and accent sets (worse of exact and RGB565 ratio). Empty = everything passes.', props: { group: 'contrast-fail' } },
  ...sections.map((id) => ({ label: `Contrast: ${id[0].toUpperCase()}${id.slice(1)}`, about: `${CP.filter((p) => p.section === id).length} pairs for the selected accent set (toolbar), dark and light side by side: sample, ratio, required minimum (kind).`, props: { group: `contrast-${id}` } }))];
// a FW_FEATURES=docs|firmware build: no page sections for hidden features' groups / contrast pairs (tools/features.mjs;
// the tokens themselves stay)
if (process.env.FW_FEATURES) {
  const F = await import('./features.mjs'), hide = F.hiddenColour(process.env.FW_FEATURES);
  // contrast sections by id; colour groups only by a feature's "colour" list (the group "surfaces" = backgrounds)
  const own = F.hiddenColour(process.env.FW_FEATURES, undefined, true);
  for (let i = doc.length - 1; i >= 0; i--) {
    const g = doc[i].props.group;
    if (g.startsWith('contrast-') ? hide.has(g.slice(9)) : own.has(g)) doc.splice(i, 1);
  }
}
L.push(`#define FW_COLOUR_SECTIONS ${cstr(JSON.stringify(doc))}`);
L.push(`#define FW_COLOUR_GROUP_IDS ${cstr(JSON.stringify(doc.map((d) => d.props.group)))}`);
L.push('// the whole tokens file (fw_tokens() hands it to the workbench page)');
L.push(`constexpr const char *JSON = R"__json__(${JSON.stringify(t)})__json__";`);
L.push('}  // namespace tokens', '}  // namespace fw', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen colour_gen.h (${names.length} colours, ${a.sets.length} accent sets)`);
