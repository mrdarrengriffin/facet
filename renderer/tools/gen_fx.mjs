#!/usr/bin/env node
// Contract core (renderer/CONTRACT.md): tokens/colour.json + space.json + type.json -> fx_gen.h, the NAME tables the
// shared token styles are built from (core/fx_core.cpp). Values are not copied: each entry points at the generated
// fw:: token (colour_gen.h Theme field, space_gen.h / type_gen.h constant for this density), so both densities and
// every theme x accent come from the one source. Names: colour "text-dim" -> styles fg:text-dim, bg:text-dim,
// border:text-dim, line:text-dim; space step 3 -> pad:3, gap:3, pad-x:3; radius card -> radius:card; layout list-row-h
// -> h:list-row-h; type label -> type:label; every size (space/layout/radius/stroke/touch) -> fx::size("stroke:hair").
// Run by build.sh / firmware/bundle.mjs: `node tools/gen_fx.mjs <out.h>`; writes only when the output changes.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const T = join(dirname(fileURLToPath(import.meta.url)), '..', 'tokens');
const rd = (f) => JSON.parse(readFileSync(join(T, f), 'utf8'));
const out = process.argv[2];
if (!out) { console.error('usage: gen_fx.mjs <out.h>'); process.exit(2); }
const field = (n) => n.replace(/-/g, '_');
const colours = Object.keys(rd('colour.json').colours);
// state colour roles (tokens/states.json -> fw::st::<state>_<role>): named "<state>-<role>" ("disabled-ink", "on-fill"),
// used like colours (fg:disabled-ink): a state look is a token too, never a colour a component works out
const roles = [];
for (const [id, s] of Object.entries(rd('states.json').states)) for (const r of Object.keys(s.roles ?? {})) roles.push([`${id}-${r}`, `fw::st::${field(id)}_${field(r)}`]);
const sp = rd('space.json');
const NS = { space: 'sp', layout: 'lay', radius: 'rad', stroke: 'stroke', touch: 'touch' };
const sizes = [];
for (const g of sp.groups.map((x) => x.id))
  for (const n of Object.keys(sp.tokens[g])) sizes.push([`${g}:${n}`, `fw::${NS[g]}::${g === 'space' ? 's' + n : field(n)}`]);
const types = Object.keys(rd('type.json').styles);
sizes.sort((a, b) => (a[0] < b[0] ? -1 : 1));
// the LOOK sizes and their ranges (theme-settable): radius 0 .. max(2 x token, 16); stroke 1 .. max(2 x token, 2);
// radius:round (999) is a sentinel, not a length: fixed. Everything else = layout (fixed: lo = hi = the token).
const range = (n, v) => n === 'radius:round' || !/^(radius|stroke):/.test(n) ? `false, ${v}, ${v}`
  : n.startsWith('radius:') ? `true, 0, (2 * ${v} > 16 ? 2 * ${v} : 16)` : `true, 1, (2 * ${v} > 2 ? 2 * ${v} : 2)`;
const o = ['// GENERATED by tools/gen_fx.mjs from tokens/colour.json, space.json, type.json: edit the JSON, not this file.',
  '#pragma once', '#include "colour_gen.h"', '#include "states_gen.h"', '#include "space_gen.h"', '#include "type_gen.h"', 'namespace fx { namespace gen {',
  'struct Colour { const char *name; lv_color_t fw::Theme::*f; };',
  `constexpr Colour COLOURS[] = {\n${colours.map((c) => `  {"${c}", &fw::Theme::${field(c)}},`).join('\n')}\n};`,
  `constexpr int N_COLOURS = ${colours.length};`,
  'struct Role { const char *name; lv_color_t (*f)(const fw::Theme &); };',
  `constexpr Role ROLES[] = {\n${roles.map(([n, f]) => `  {"${n}", &${f}},`).join('\n')}\n};`,
  `constexpr int N_ROLES = ${roles.length};`,
  '// sorted by name; device px at this density. look = a LOOK size (radius:*, stroke:*): a theme may set it within lo..hi;',
  '// every other size is a LAYOUT size, fixed by Facet (lo = hi = v: renderer/CONTRACT.md "Size tokens: layout vs look")',
  'struct Size { const char *name; int v; bool look; int lo, hi; };',
  `constexpr Size SIZES[] = {\n${sizes.map(([n, v]) => `  {"${n}", ${v}, ${range(n, v)}},`).join('\n')}\n};`,
  `constexpr int N_SIZES = ${sizes.length};`,
  'struct Type { const char *name; fw::ty::Id id; };',
  `constexpr Type TYPES[] = {\n${types.map((t) => `  {"${t}", fw::ty::${field(t)}},`).join('\n')}\n};`,
  `constexpr int N_TYPES = ${types.length};`, '}}  // namespace fx::gen', ''];
const s = o.join('\n');
if (!existsSync(out) || readFileSync(out, 'utf8') !== s) writeFileSync(out, s);
