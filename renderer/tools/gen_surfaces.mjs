#!/usr/bin/env node
// tokens/surfaces.json -> C++ header surfaces_gen.h: fw::sf:: the Sports surfaces foundation (surfaces + venue presets
// as colour.json Theme fields + the mark mix index, the line rule, tennis / pitch geometry in metres, the rules in plain
// words for the page). Run by build.sh: `node tools/gen_surfaces.mjs <out.h>`; writes only when the output changes.
// Fails on unknown colour tokens / mixes / surfaces, a court colour without its mark mix, or a missing about.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const rd = (f) => JSON.parse(readFileSync(join(HERE, '..', 'tokens', f), 'utf8'));
const t = rd('surfaces.json'), col = rd('colour.json'), spc = rd('space.json');
const out = process.argv[2];
if (!out) { console.error('usage: gen_surfaces.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/surfaces.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');
const colour = (n) => { if (!col.colours[n]) die(`unknown colour token ${n}`); return `&Theme::${field(n)}`; };
const mixes = Object.keys(col.mixes ?? {});
const mixOf = (court) => { const n = `${t.mark.mix}-${court.replace(/^court-/, '')}`; const i = mixes.indexOf(n); if (i < 0) die(`court ${court}: mark mix ${n} missing in colour.json mixes`); return i; };
const strokes = spc.tokens?.stroke;
const stroke = (n) => { if (!strokes?.[n]) die(`unknown stroke ${n}`); return `stroke::${field(n)}`; };

const L = ['// generated by tools/gen_surfaces.mjs from tokens/surfaces.json: do not edit', '#pragma once', '#include "colour_gen.h"', 'namespace fw::sf {'];
L.push('using Ink = lv_color_t Theme::*;');
L.push('// a surface or a venue preset: court + run-off colour, optional mowing stripes (bands per half court, across)');
L.push('struct Surface { const char *id, *label, *about, *base; Ink court, out, stripe; int stripes; bool venue; };');
const rows = [];
for (const [id, s] of Object.entries(t.surfaces)) {
  if (!s.about || !s.label) die(`surfaces.${id}: label + about`);
  rows.push({ id, label: s.label, about: s.about, base: id, court: s.court, out: s.out, stripe: s.stripes?.colour, n: s.stripes?.['per-half'] ?? 0, venue: false });
}
for (const [id, v] of Object.entries(t.venues)) {
  const b = t.surfaces[v.surface];
  if (!b) die(`venues.${id}: unknown surface ${v.surface}`);
  if (!v.about || !v.label) die(`venues.${id}: label + about`);
  rows.push({ id, label: v.label, about: v.about, base: v.surface, court: v.court ?? b.court, out: v.out ?? b.out, stripe: v.stripes?.colour, n: v.stripes?.['per-half'] ?? 0, venue: true });
}
L.push(`constexpr int N_SURFACES = ${rows.length}, N_BASES = ${Object.keys(t.surfaces).length};  // bases first, then venues`, 'constexpr Surface SURFACES[N_SURFACES] = {');
for (const r of rows) {
  if (r.stripe && !(r.n > 0 && r.n <= 12)) die(`${r.id}: stripes per-half 1..12`);
  mixOf(r.court); if (r.stripe) mixOf(r.stripe);  // the mark mixes the contrast test checks lines on
  L.push(`  {${cstr(r.id)}, ${cstr(r.label)}, ${cstr(r.about)}, ${cstr(r.base)}, ${colour(r.court)}, ${colour(r.out)}, ${r.stripe ? colour(r.stripe) : 'nullptr'}, ${r.n}, ${r.venue}},`);
}
L.push('};');
L.push(`inline Ink line_ink() { return ${colour(t.line.colour)}; }`, `constexpr int LINE_W = ${stroke(t.line.weight)}, NET_W = ${stroke(t.line.net)};  // device px`);
if (!(t.rules?.length)) die('rules missing');
L.push('struct Rule { const char *id, *title, *about; };', `constexpr int N_RULES = ${t.rules.length};`, 'constexpr Rule RULES[N_RULES] = {');
for (const r of t.rules) { if (!r.about || !r.title) die(`rules.${r.id}: title + about`); L.push(`  {${cstr(r.id)}, ${cstr(r.title)}, ${cstr(r.about)}},`); }
L.push('};');
const g = t.tennis;
for (const k of ['length', 'width', 'singles', 'service', 'post', 'runoff-back', 'runoff-side']) if (!(g[k] > 0)) die(`tennis.${k} must be > 0 metres`);
L.push('namespace tennis {  // ITF metres', ...['length', 'width', 'singles', 'service', 'post', 'runoff-back', 'runoff-side'].map((k) => `constexpr float ${field(k)} = ${g[k]}f;`), '}  // namespace tennis');
L.push(`constexpr const char *DATA_NOTE = ${cstr(`${t.data['api-tennis']}; ${t.data.espn}; ${t.data.default}`)};`);
L.push('}  // namespace fw::sf', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen surfaces_gen.h (${rows.length} surfaces + venues, ${t.rules.length} rules)`);
