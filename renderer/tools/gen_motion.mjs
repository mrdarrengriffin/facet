#!/usr/bin/env node
// tokens/motion.json -> C++ header (README "Motion tokens"): fw::mo::ms:: durations (ms), fw::mo::ease:: easing path
// callbacks (an LVGL built-in when the JSON names one and its curve matches LVGL's exactly, else a generated cubic
// bezier path function), fw::mo::Id patterns (press, sheet_open, ...) + the PATTERNS table (duration, easing, offset
// px for this density, stagger, reduced-motion mode), and the tables of the Motion page. Run by build.sh /
// firmware/bundle.mjs: `node tools/gen_motion.mjs <out.h>`; writes only when the output changes.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(HERE, '..', 'tokens', 'motion.json'), 'utf8'));
const out = process.argv[2];
if (!out) { console.error('usage: gen_motion.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/motion.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');
const name = (n, what) => { if (!/^[a-z][a-z0-9-]*$/.test(n)) die(`${what} ${n}: bad name`); return field(n); };

// LVGL 9.5 built-in paths and the cubic bezier each one runs (lv_anim.c): a JSON easing naming one must match it
const LVGL = {
  lv_anim_path_linear: [0, 0, 1, 1],
  lv_anim_path_ease_out: [0, 0, 0.58, 1],
  lv_anim_path_ease_in_out: [0.42, 0, 0.58, 1],
  lv_anim_path_ease_in: [0.42, 0, 1, 1],
};
const groups = t.groups.map((g) => g.id);
const durs = Object.entries(t.durations).map(([n, d]) => {
  name(n, 'duration');
  if (!Number.isInteger(d.ms) || d.ms <= 0) die(`duration ${n}: ms must be a positive integer`);
  if (!groups.includes(d.group)) die(`duration ${n}: unknown group ${d.group}`);
  return { n, ...d };
});
const eases = Object.entries(t.easings).map(([n, e]) => {
  name(n, 'easing');
  const b = e.bezier;
  if (!Array.isArray(b) || b.length !== 4 || b.some((v) => typeof v !== 'number')) die(`easing ${n}: bezier = [x1, y1, x2, y2]`);
  if (b[0] < 0 || b[0] > 1 || b[2] < 0 || b[2] > 1) die(`easing ${n}: bezier x1 / x2 must be within 0..1`);
  if (e.lvgl) {
    const ref = LVGL[e.lvgl];
    if (!ref) die(`easing ${n}: ${e.lvgl} is not a known LVGL path (${Object.keys(LVGL).join(', ')}); drop "lvgl" to get a generated path`);
    if (ref.some((v, i) => Math.abs(v - b[i]) > 1e-9)) die(`easing ${n}: ${e.lvgl} runs cubic-bezier(${ref}), not (${b}); drop "lvgl" to get a generated path`);
  }
  return { n, ...e };
});
const MODES = Object.keys(t.reduced.modes);
for (const m of ['keep', 'fade', 'instant', 'still']) if (!MODES.includes(m)) die(`reduced.modes: ${m} missing`);
const pats = Object.entries(t.patterns).map(([n, p]) => {
  name(n, 'pattern');
  const d = t.durations[p.duration];
  if (!d) die(`pattern ${n}: unknown duration ${p.duration}`);
  if (!t.easings[p.easing]) die(`pattern ${n}: unknown easing ${p.easing}`);
  if (!MODES.includes(p.reduced)) die(`pattern ${n}: reduced must be one of ${MODES.join(', ')}`);
  const off = p.offset ?? { v: 0, '1x': 0 };
  for (const k of ['v', '1x']) if (!Number.isInteger(off[k]) || off[k] % 4) die(`pattern ${n}: offset.${k} = ${off[k]} not on the 4 px grid`);
  return { n, ...p, ms: d.ms, off, stagger: p.stagger ?? 0, steps: p['max-steps'] ?? 1 };
});
const reduceFade = t.durations.fade?.ms ?? 150;

const L = ['// GENERATED by tools/gen_motion.mjs from tokens/motion.json: edit the JSON, not this file.', '#pragma once', '#include <cstdint>', '#include "lvgl.h"', '', 'namespace fw::mo {'];
L.push('namespace ms {  // durations, ms');
for (const d of durs) L.push(`constexpr uint32_t ${field(d.n)} = ${d.ms};  // ${d.use}`);
L.push('}  // namespace ms');
L.push('namespace ease {  // easing path callbacks (lv_anim_path_cb_t): LVGL built-ins where they match, else generated');
const B = (v) => Math.round(v * 1024);  // LV_BEZIER_VAL_MAX = 1024
for (const e of eases) {
  if (e.lvgl) L.push(`inline const lv_anim_path_cb_t ${field(e.n)} = ${e.lvgl};  // ${e.css}`);
  else {
    const [x1, y1, x2, y2] = e.bezier.map(B);
    L.push(`inline int32_t path_${field(e.n)}(const lv_anim_t *a) {  // ${e.css}: lv_cubic_bezier, like lv_anim_path_ease_out`);
    L.push(`  const int32_t t = lv_map(a->act_time, 0, a->duration, 0, 1024);`);
    L.push(`  const int32_t s = lv_cubic_bezier(t, ${x1}, ${y1}, ${x2}, ${y2});`);
    L.push(`  return a->start_value + (int32_t) (((int64_t) s * (a->end_value - a->start_value)) >> 10);`);
    L.push('}');
    L.push(`inline const lv_anim_path_cb_t ${field(e.n)} = path_${field(e.n)};`);
  }
}
L.push('}  // namespace ease');
L.push(`enum Easing { ${eases.map((e) => `E_${field(e.n)}`).join(', ')}, N_EASINGS };`);
L.push(`enum Reduced { ${MODES.map((m) => `R_${m}`).join(', ')} };`);
L.push(`enum Id { ${pats.map((p) => field(p.n)).join(', ')}, N };  // patterns`);
L.push(`constexpr uint32_t REDUCED_FADE_MS = ${reduceFade};  // reduced "fade": opacity only, at most this long`);
L.push('struct Pattern { const char *id, *label; uint32_t ms; Easing easing; int offset; uint32_t stagger; int steps; Reduced reduced; const char *duration, *animates, *use; };');
const pat = (d) => pats.map((p) => `  {${cstr(p.n)}, ${cstr(p.label)}, ${p.ms}, E_${field(p.easing)}, ${d === '1x' ? p.off['1x'] : p.off.v}, ${p.stagger}, ${p.steps}, R_${p.reduced}, ${cstr(p.duration)}, ${cstr(p.animates)}, ${cstr(p.use)}},`);
L.push('#ifdef FW_1X', 'constexpr Pattern PATTERNS[N] = {', ...pat('1x'), '};', '#else', 'constexpr Pattern PATTERNS[N] = {', ...pat('v'), '};', '#endif');
L.push('struct EasingDef { const char *id, *css, *lvgl, *use; lv_anim_path_cb_t path; float x1, y1, x2, y2; };');
L.push('inline const EasingDef EASINGS[N_EASINGS] = {');
for (const e of eases) L.push(`  {${cstr(e.n)}, ${cstr(e.css)}, ${cstr(e.lvgl || 'generated cubic bezier')}, ${cstr(e.use)}, ease::${field(e.n)}, ${e.bezier.map((v) => `${Number(v).toFixed(2)}f`).join(', ')}},`);
L.push('};');
L.push('struct Group { const char *id, *label, *about; };', 'constexpr Group GROUPS[] = {');
for (const g of t.groups) L.push(`  {${cstr(g.id)}, ${cstr(g.label)}, ${cstr(g.about)}},`);
L.push('};', `constexpr int N_GROUPS = ${t.groups.length};`);
L.push('struct Duration { const char *id, *group, *use; uint32_t ms; };', 'constexpr Duration DURATIONS[] = {');
for (const d of durs) L.push(`  {${cstr(d.n)}, ${cstr(d.group)}, ${cstr(d.use)}, ${d.ms}},`);
L.push('};', `constexpr int N_DURATIONS = ${durs.length};`);
L.push(`constexpr const char *REDUCED_ABOUT = ${cstr(t.reduced.about)};`);
L.push(`constexpr const char *REDUCED_MODES[] = {${MODES.map((m) => cstr(t.reduced.modes[m])).join(', ')}};`);
L.push(`constexpr const char *REDUCED_NAMES[] = {${MODES.map(cstr).join(', ')}};`);
for (const [n, o] of Object.entries(t.opacity ?? {})) L.push(`constexpr float OPA_${field(n).toUpperCase()} = ${o.value}f;  // ${o.use}`);
const doc = [
  { label: 'Easing curves', about: `Each curve plotted (time across, progress up) with a dot running along it and a box moving with it, slowed to 1 s so the shape reads. Tap a curve to replay. ${eases.length} easings; every Facet curve is an LVGL built-in, others get a generated path.`, props: { section: 'easing' } },
  { label: 'Durations', about: `${durs.length} named durations as bars (interaction on one scale, ambient loops on a log scale). Tap a bar to run it at its real length.`, props: { section: 'durations' } },
  { label: 'Patterns', about: `${pats.length} named patterns, each = duration + easing + what moves, live on a sample. Tap a sample to play it; the reduced_motion setting in the playground shows each one with reduced motion.`, props: { section: 'patterns' } },
  { label: 'Reduced motion', about: 'What each pattern does when reduced motion is on.', props: { section: 'reduced' } },
];
L.push(`#define FW_MOTION_SECTIONS ${cstr(JSON.stringify(doc))}`);
L.push(`#define FW_MOTION_SECTION_IDS ${cstr(JSON.stringify(doc.map((d) => d.props.section)))}`);
L.push(`#define FW_MOTION_PATTERN_IDS ${cstr(JSON.stringify(['off', ...pats.map((p) => p.n)]))}`);
L.push('}  // namespace fw::mo', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen motion_gen.h (${durs.length} durations, ${eases.length} easings, ${pats.length} patterns)`);
