#!/usr/bin/env node
// tokens/settings.json -> settings_gen.h (fw::set::): the personalisation settings schema for the renderer (README
// "Settings schema"). Checks: accent option ids = tokens/colour.json accent sets, sound pack option ids = tokens/sound.json
// variants, defaults are valid, presets inside min..max. Also emits the Settings screen's playground props (one per
// setting, the value) as JSON. Writes only when the output changes (an unchanged schema rebuilds nothing).
// Usage: node gen_settings.mjs <out.h>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const T = join(HERE, '..', 'tokens');
const out = process.argv[2];
if (!out) { console.error('usage: gen_settings.mjs <out.h>'); process.exit(1); }
const S = JSON.parse(readFileSync(join(T, 'settings.json'), 'utf8'));
const colour = JSON.parse(readFileSync(join(T, 'colour.json'), 'utf8'));
const sound = JSON.parse(readFileSync(join(T, 'sound.json'), 'utf8'));
const fail = (m) => { console.error(`gen_settings: ${m}`); process.exit(1); };

const KINDS = { select: 'SELECT', switch: 'SWITCH', number: 'NUMBER' };
const CONTROLS = { segmented: 'SEGMENTED', swatches: 'SWATCHES', toggle: 'TOGGLE', sheet: 'SHEET', presets: 'PRESETS', slider: 'SLIDER' };
const accentIds = colour.accent.sets.map((s) => s.id);
const packIds = sound.variants.map((v) => (typeof v === 'string' ? v : v.id));
const groups = S.groups.map((g) => g.id);
const q = (s) => JSON.stringify(s ?? '');

for (const s of S.settings) {
  if (!groups.includes(s.group)) fail(`${s.id}: unknown group ${s.group}`);
  if (!KINDS[s.kind]) fail(`${s.id}: unknown kind ${s.kind}`);
  if (!CONTROLS[s.control]) fail(`${s.id}: unknown control ${s.control}`);
  const ids = (s.options ?? []).map((o) => o.id);
  if (s.kind === 'select' && !ids.includes(s.default)) fail(`${s.id}: default ${s.default} is not an option`);
  if (s.id === 'accent' && ids.join() !== accentIds.join()) fail(`accent options ${ids} != colour.json accent sets ${accentIds}`);
  if (s.id === 'soundPack' && ids.join() !== packIds.join()) fail(`soundPack options ${ids} != sound.json variants ${packIds}`);
  if (s.kind === 'number') {
    if (s.default < s.min || s.default > s.max) fail(`${s.id}: default outside ${s.min}..${s.max}`);
    for (const p of s.presets ?? []) if (p < s.min || p > s.max) fail(`${s.id}: preset ${p} outside ${s.min}..${s.max}`);
    if (s.control === 'presets' && !(s.presets ?? []).includes(s.default)) fail(`${s.id}: default is not a preset`);
  }
}

const L = ['// GENERATED by tools/gen_settings.mjs from tokens/settings.json: edit the JSON, not this file.', '#pragma once', 'namespace fw {', 'namespace set {'];
L.push('enum Kind { SELECT, SWITCH, NUMBER };', 'enum Control { SEGMENTED, SWATCHES, TOGGLE, SHEET, PRESETS, SLIDER };');
L.push('struct Option { const char *id, *label, *hint; };', 'struct Group { const char *id, *label; };');
L.push('struct Setting {', '  const char *id, *group, *label, *about;', '  Kind kind;', '  Control control;', '  const Option *options;', '  int n_options;',
  '  const char *def;  // default: option id, "true" / "false", or the number', '  double min, max, step;', '  const char *unit, *zero;  // zero = the word for 0 ("Never")', '  const double *presets;', '  int n_presets;', '};');
L.push('constexpr Group GROUPS[] = {', ...S.groups.map((g) => `    {${q(g.id)}, ${q(g.label)}},`), '};', `constexpr int N_GROUPS = ${S.groups.length};`);
for (const s of S.settings) {
  if (s.options) L.push(`constexpr Option OPT_${s.id}[] = {${s.options.map((o) => `{${q(o.id)}, ${q(o.label)}, ${q(o.hint)}}`).join(', ')}};`);
  if (s.presets) L.push(`constexpr double PRE_${s.id}[] = {${s.presets.join(', ')}};`);
}
L.push('constexpr Setting SETTINGS[] = {');
for (const s of S.settings)
  L.push(`    {${q(s.id)}, ${q(s.group)}, ${q(s.label)}, ${q(s.about)}, ${KINDS[s.kind]}, ${CONTROLS[s.control]}, ${s.options ? `OPT_${s.id}` : 'nullptr'}, ${s.options?.length ?? 0}, ` +
    `${q(String(s.default))}, ${s.min ?? 0}, ${s.max ?? 0}, ${s.step ?? 1}, ${q(s.unit)}, ${q(s.zero)}, ${s.presets ? `PRE_${s.id}` : 'nullptr'}, ${s.presets?.length ?? 0}},`);
L.push('};', `constexpr int N_SETTINGS = ${S.settings.length};`);
// playground props of the Settings screen: one per setting (its value), in schema order
const props = S.settings.map((s) => {
  if (s.kind === 'switch') return { name: s.id, type: 'bool', default: !!s.default };
  if (s.kind === 'number' && s.control === 'slider') return { name: s.id, type: 'range', min: s.min, max: s.max, step: s.step, default: s.default };
  if (s.kind === 'number') return { name: s.id, type: 'select', options: s.presets.map(String), default: String(s.default) };
  if (s.id === 'accent') return { name: s.id, type: 'select', options: ['current', ...s.options.map((o) => o.id)], default: 'current' };
  return { name: s.id, type: 'select', options: s.options.map((o) => o.id), default: s.default };
});
L.push(`constexpr const char *PROPS_JSON = R"(${JSON.stringify(props)})";`);
L.push('}  // namespace set', '}  // namespace fw', '');
const text = L.join('\n');
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text);
