#!/usr/bin/env node
// tokens/chart.json -> C++ header chart_gen.h: fw::ch:: series + role colours (colour.json token -> Theme field),
// geometry as device px for this density (#ifdef FW_1X), the area mixes, chart motion (motion.json durations and
// easings resolved by name), lite + reduced modes, and the Charts page sections. Run by build.sh:
// `node tools/gen_chart.mjs <out.h>`; writes only when the output changes. Fails on unknown tokens / off-grid values.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const rd = (f) => JSON.parse(readFileSync(join(HERE, '..', 'tokens', f), 'utf8'));
const t = rd('chart.json'), col = rd('colour.json'), mot = rd('motion.json');
const out = process.argv[2];
if (!out) { console.error('usage: gen_chart.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/chart.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');
const colour = (n) => { if (!col.colours[n]) die(`unknown colour token ${n}`); return `t.${field(n)}`; };
const mixes = Object.keys(col.mixes ?? {});
const mixIdx = (n) => { const i = mixes.indexOf(n); if (i < 0) die(`unknown colour mix ${n}`); return i; };

const L = ['// generated by tools/gen_chart.mjs from tokens/chart.json: do not edit', '#pragma once', '#include "colour_gen.h"', '#include "motion_gen.h"', 'namespace fw::ch {'];
// series + roles
L.push('struct Series { const char *id, *token, *label, *use; bool dashed; };', `constexpr int N_SERIES = ${t.series.length};`, 'constexpr Series SERIES[N_SERIES] = {');
for (const s of t.series) { colour(s.token); L.push(`  {${cstr(s.id)}, ${cstr(s.token)}, ${cstr(s.label)}, ${cstr(s.use)}, ${!!s.dashed}},`); }
L.push('};', 'inline lv_color_t series(const Theme &t, int i) {', '  switch (i) {');
t.series.forEach((s, i) => L.push(`    case ${i}: return ${colour(s.token)};`));
L.push(`    default: return ${colour(t.series[0].token)};`, '  }', '}');
L.push('struct Role { const char *id, *token, *use, *about; };', 'constexpr Role ROLES[] = {');
for (const [n, r] of Object.entries(t.roles)) { colour(r.token); if (!r.about) die(`roles.${n}: about (plain words for the page) missing`); L.push(`  {${cstr(n)}, ${cstr(r.token)}, ${cstr(r.use)}, ${cstr(r.about)}},`); }
L.push('};', `constexpr int N_ROLES = ${Object.keys(t.roles).length};`);
L.push('namespace ink {  // role colours: ch::ink::grid(*T)');
for (const [n, r] of Object.entries(t.roles)) L.push(`inline lv_color_t ${field(n)}(const Theme &t) { return ${colour(r.token)}; }  // ${r.token}`);
L.push('}  // namespace ink', 'inline lv_color_t ink_of(const Theme &t, int i) {  // role i of ROLES', '  switch (i) {');
Object.values(t.roles).forEach((r, i) => L.push(`    case ${i}: return ${colour(r.token)};`));
L.push(`    default: return ${colour(Object.values(t.roles)[0].token)};`, '  }', '}');
L.push(`constexpr int AREA_MIX = ${mixIdx(t.area.mix)}, AREA_MIX_BG = ${mixIdx(t.area['mix-bg'])};  // fw::tokens::MIXES`);
L.push(`constexpr float AREA_OPA = ${col.components.chart.area.value}f;`, `constexpr const char *AREA_USE = ${cstr(t.area.use)};`, `constexpr const char *AREA_ABOUT = ${cstr(t.area.about)};`);
L.push(`constexpr int GRID_LINES = ${t['grid-lines']};`);
// geometry: 4 px grid, strokes 1-2 or even (space.json rule)
const geo = Object.entries(t.geometry);
const stroke = new Set(['line', 'line-thin', 'grid', 'dash', 'dash-gap', 'gauge-track', 'gauge-ind']);
for (const [n, g] of geo)
  for (const d of ['v', '1x']) {
    const v = g[d];
    if (!Number.isInteger(v) || v < 0) die(`geometry.${n}.${d} must be a whole px`);
    if (n === 'dash' || n === 'dash-gap') continue;
    if (stroke.has(n) ? !(v <= 2 || v % 2 === 0) : v % 4) die(`geometry.${n}.${d} = ${v} is off the grid`);
  }
const gl = (d) => geo.map(([n, g]) => `constexpr int ${field(n)} = ${g[d]};  // ${g.use}`);
L.push('#ifdef FW_1X', ...gl('1x'), '#else', ...gl('v'), '#endif');
L.push('struct Geo { const char *id, *use; int v, x1; };', 'constexpr Geo GEOMETRY[] = {');
for (const [n, g] of geo) L.push(`  {${cstr(n)}, ${cstr(g.use)}, ${g.v}, ${g['1x']}},`);
L.push('};', `constexpr int N_GEOMETRY = ${geo.length};`);
// motion
const EASE = Object.keys(mot.easings), RED = ['keep', 'fade', 'instant', 'still'], LITE = Object.keys(t.lite.modes);
const ms = Object.entries(t.motion);
L.push(`enum Lite { ${LITE.map((m) => `L_${m}`).join(', ')} };`, `enum MId { ${ms.map(([n]) => `M_${field(n)}`).join(', ')}, N_MOTION };`);
L.push('struct Motion { const char *id, *label; uint32_t ms; mo::Easing easing; uint32_t stagger; mo::Reduced reduced; Lite lite; const char *duration, *animates, *use, *cost; };', 'constexpr Motion MOTION[N_MOTION] = {');
for (const [n, m] of ms) {
  const d = mot.durations[m.duration];
  if (!d) die(`motion.${n}: unknown duration ${m.duration}`);
  if (!EASE.includes(m.easing)) die(`motion.${n}: unknown easing ${m.easing}`);
  if (!m.cost) die(`motion.${n}: cost (plain words for the page) missing`);
  if (!RED.includes(m.reduced) || !LITE.includes(m.lite)) die(`motion.${n}: bad reduced / lite mode`);
  L.push(`  {${cstr(n)}, ${cstr(m.label)}, ${d.ms}, mo::E_${field(m.easing)}, ${m.stagger ?? 0}, mo::R_${m.reduced}, L_${m.lite}, ${cstr(m.duration)}, ${cstr(m.animates)}, ${cstr(m.use)}, ${cstr(m.cost)}},`);
}
L.push('};', `constexpr const char *LITE_ABOUT = ${cstr(t.lite.about)};`, `constexpr const char *LITE_SAY = ${cstr(t.lite.say)};`, `constexpr const char *LITE_MODES[] = {${LITE.map((m) => cstr(t.lite.modes[m])).join(', ')}};`, `constexpr const char *LITE_NAMES[] = {${LITE.map(cstr).join(', ')}};`);
// sound: the scrub pitch range (a share of sound.json pitch)
const sp = t.sound?.['scrub-pitch'];
if (!sp || !(sp.low >= 0 && sp.high <= 1 && sp.low < sp.high)) die('sound.scrub-pitch: low < high, both 0..1');
if (!sp.about) die('sound.scrub-pitch: about (plain words for the page) missing');
L.push(`constexpr float SCRUB_PITCH_LOW = ${sp.low}f, SCRUB_PITCH_HIGH = ${sp.high}f;  // share of sound.json pitch: the line's bottom / top`, `constexpr const char *SCRUB_PITCH_ABOUT = ${cstr(sp.about)};`);
L.push('inline lv_anim_path_cb_t path(MId m) { return mo::EASINGS[MOTION[m].easing].path; }');
const doc = [
  { label: 'Series colours', about: 'Up to three series colours, a compare style and a highlight, on a card and on the canvas, in both themes. Every one passes contrast against what it sits on; the legend always names them.', props: { section: 'colours' } },
  { label: 'Lines, areas and grid', about: 'Line weights for each panel, the fill under a single line, grid lines and the baseline, dots and the now marker.', props: { section: 'lines' } },
  { label: 'Bars and gauges', about: 'Bars with a rounded data end and a square foot, the highlighted latest bar, compare bars, and a gauge.', props: { section: 'bars' } },
  { label: 'Labels and units', about: 'Big number with its unit, axis labels, legend and the scrub readout. Press and drag across a chart to read it.', props: { section: 'labels' } },
  { label: 'No data, unavailable, loading', about: 'What a chart shows before it has data, when its sensor is gone, while history loads, and with gaps.', props: { section: 'states' } },
];
L.push(`#define FW_CHART_SECTIONS ${cstr(JSON.stringify(doc))}`, `#define FW_CHART_SECTION_IDS ${cstr(JSON.stringify(doc.map((d) => d.props.section)))}`);
L.push('}  // namespace fw::ch', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen chart_gen.h (${t.series.length} series, ${geo.length} sizes, ${ms.length} motions)`);
