#!/usr/bin/env node
// tokens/space.json -> C++ header: fw::sp:: (grid + spacing steps), fw::lay:: (screen layout), fw::rad::, fw::stroke::,
// fw::touch:: as device px for this density (#ifdef FW_1X), the token table for the Spacing & radius page (both
// densities) and its sections. Run by build.sh / firmware/bundle.mjs: `node tools/gen_space.mjs <out.h>`; writes only
// when the output changes.
import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(HERE, '..', 'tokens', 'space.json'), 'utf8'));
const out = process.argv[2];
if (!out) { console.error('usage: gen_space.mjs <out.h>'); process.exit(2); }
const die = (m) => { console.error(`tokens/space.json: ${m}`); process.exit(1); };
const cstr = (s) => JSON.stringify(String(s ?? ''));
const field = (n) => n.replace(/-/g, '_');
const NS = { space: 'sp', layout: 'lay', radius: 'rad', stroke: 'stroke', touch: 'touch' };
const groups = t.groups.map((g) => g.id);
for (const g of groups) if (!NS[g] || !t.tokens[g]) die(`group ${g}: unknown or without tokens`);
const rows = [];
for (const g of groups)
  for (const [n, v] of Object.entries(t.tokens[g])) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(n)) die(`${g}.${n}: bad name`);
    if (!Number.isInteger(v.v) || !Number.isInteger(v['1x'])) die(`${g}.${n}: v and 1x must be integers`);
    rows.push({ g, n, ...v });
  }
const steps = Object.keys(t.tokens.space).map(Number).sort((a, b) => a - b);
steps.forEach((s, i) => { if (s !== i + 1) die('space steps must be 1..N'); });

const L = ['// GENERATED by tools/gen_space.mjs from tokens/space.json: edit the JSON, not this file.', '#pragma once', '', 'namespace fw {'];
const block = (d) => {
  const val = (r) => (d === '1x' ? r['1x'] : r.v);
  const B = [];
  B.push('namespace sp {', `constexpr int GRID = ${t.grid[d === '1x' ? '1x' : '1.5x']};`);
  B.push(`constexpr int N = ${steps.length + 1};  // steps 0..${steps.length}`);
  B.push(`constexpr int S[N] = {0, ${steps.map((s) => val(t.tokens.space[s])).join(', ')}};`);
  for (const s of steps) B.push(`constexpr int s${s} = ${val(t.tokens.space[s])};`);
  B.push('}  // namespace sp');
  for (const g of groups.filter((g) => g !== 'space')) {
    B.push(`namespace ${NS[g]} {`);
    for (const r of rows.filter((r) => r.g === g)) B.push(`constexpr int ${field(r.n)} = ${val(r)};`);
    B.push(`}  // namespace ${NS[g]}`);
  }
  return B;
};
L.push('#ifdef FW_1X', ...block('1x'), '#else', ...block('1.5x'), '#endif');
L.push('namespace spt {  // the token table (Spacing & radius page): both densities, px');
L.push('struct Group { const char *id, *ns, *label, *about, *source1x; };', 'constexpr Group GROUPS[] = {');
for (const g of t.groups) L.push(`  {${cstr(g.id)}, ${cstr(NS[g.id])}, ${cstr(g.label)}, ${cstr(g.about)}, ${cstr(g.source1x)}},`);
L.push('};', `constexpr int N_GROUPS = ${t.groups.length};`);
L.push('struct Token { const char *group, *name, *use; int v, v1x; };', 'constexpr Token TOKENS[] = {');
for (const r of rows) L.push(`  {${cstr(r.g)}, ${cstr(r.n)}, ${cstr(r.use)}, ${r.v}, ${r['1x']}},`);
L.push('};', `constexpr int N_TOKENS = ${rows.length};`);
L.push(`constexpr int GRID_REF = ${t.grid['1.5x']}, GRID_1X = ${t.grid['1x']};`);
L.push(`constexpr const char *GRID_ABOUT = ${cstr(t.grid.about)};`);
L.push(`constexpr int HOME_COLS = ${t.columns.home}, TILE_COLS = ${t.columns.tiles};`);
L.push(`constexpr const char *COLUMNS_ABOUT = ${cstr(t.columns.about)};`);
L.push('}  // namespace spt');
const doc = [
  ...t.groups.map((g) => ({ label: g.label, about: `${g.about} 480 values: ${g.source1x}.`, props: { section: g.id } })),
  { label: 'Screen inset and grid', about: `The whole screen at true size: the ${t.grid['1.5x']} px grid (${t.grid['1x']} px at 480), the inset, the header row, where content starts and the Home columns. ${t.columns.about}`, props: { section: 'screen' } },
];
L.push(`#define FW_SPACE_SECTIONS ${cstr(JSON.stringify(doc))}`);
L.push(`#define FW_SPACE_SECTION_IDS ${cstr(JSON.stringify(doc.map((d) => d.props.section)))}`);
L.push('}  // namespace fw', '');
const text = L.join('\n');
if (existsSync(out) && readFileSync(out, 'utf8') === text) process.exit(0);
writeFileSync(`${out}.${process.pid}`, text);
renameSync(`${out}.${process.pid}`, out);
console.log(`gen space_gen.h (${rows.length} tokens)`);
