#!/usr/bin/env node
// tokens/settings.json -> an ESPHome package (README "Device firmware", "Settings on the panel"): every personalisation
// setting as a config-category entity (select / switch / number) that keeps its value in NVS (restore), so it survives
// a reboot and Home Assistant can see and change it. Each entity and the panel's Settings screen go through the ONE
// set() path (core/device.h "settings", fw::dev::set): an entity's new value -> set(id, value, HA); a change made
// anywhere else (the screen, POST /fw/settings) -> the observer below moves the entity (which saves it). set() ignores
// an unchanged value, so nothing echoes. Theme Auto follows Home Assistant's sun.sun (above_horizon = day).
// Usage: node firmware/settings_yaml.mjs <out.yaml>   (bin/panel `wb build` runs it; writes only on change)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const out = process.argv[2];
if (!out) { console.error('usage: settings_yaml.mjs <out.yaml>'); process.exit(1); }
const S = JSON.parse(readFileSync(join(HERE, '..', 'renderer', 'tokens', 'settings.json'), 'utf8'));
const q = (s) => JSON.stringify(String(s));
const ent = (s) => s.esphome ?? { id: s.id, name: s.label };
const L = ['# GENERATED by facet-wasm firmware/settings_yaml.mjs from renderer/tokens/settings.json: edit the JSON, not this file.',
  '# Facet panel settings: config entities restored from NVS, one set() path (core/device.h "settings").', ''];

const sel = S.settings.filter((s) => s.kind === 'select'), sw = S.settings.filter((s) => s.kind === 'switch'), nm = S.settings.filter((s) => s.kind === 'number');
// esphome.internal: true = kept, restored and applied but not shown in Home Assistant (a setting the firmware does not
// act on yet: no knob without an effect); esphome.device_class (number: "duration" = HA shows "5 min")
const common = (s) => [`    id: ${ent(s).id}`, `    name: ${q(ent(s).name)}`, ...(ent(s).icon ? [`    icon: ${q(ent(s).icon)}`] : []), '    entity_category: config', '    optimistic: true',
  ...(ent(s).internal ? ['    internal: true'] : []), ...(ent(s).device_class ? [`    device_class: ${ent(s).device_class}`] : [])];
L.push('select:');
for (const s of sel) {
  const def = s.options.find((o) => o.id === s.default).label;
  L.push('  - platform: template', ...common(s), `    options: [${s.options.map((o) => q(o.label)).join(', ')}]`, `    initial_option: ${q(def)}`,
    '    restore_value: true', `    on_value:`, `      - lambda: 'fw::dev::set(${q(s.id)}, x.c_str(), fw::dev::HA);'`);
}
L.push('', 'switch:');
for (const s of sw)
  L.push('  - platform: template', ...common(s), `    restore_mode: ${s.default ? 'RESTORE_DEFAULT_ON' : 'RESTORE_DEFAULT_OFF'}`,
    `    on_turn_on:`, `      - lambda: 'fw::dev::set(${q(s.id)}, "true", fw::dev::HA);'`,
    `    on_turn_off:`, `      - lambda: 'fw::dev::set(${q(s.id)}, "false", fw::dev::HA);'`);
L.push('', 'number:');
for (const s of nm)
  L.push('  - platform: template', ...common(s), `    min_value: ${s.min}`, `    max_value: ${s.max}`, `    step: ${s.step}`, `    initial_value: ${s.default}`,
    ...(s.unit ? [`    unit_of_measurement: ${q(s.unit)}`] : []), `    mode: ${s.control === 'slider' ? 'slider' : 'box'}`, '    restore_value: true',
    `    on_value:`, `      - lambda: 'fw::dev::set(${q(s.id)}, (double) x, fw::dev::HA);'`);

// Theme Auto: day / night from Home Assistant
L.push('', 'text_sensor:', '  - platform: homeassistant', '    id: facet_sun', '    entity_id: sun.sun', '    internal: true',
  '    on_value:', `      - lambda: 'fw::dev::set_daylight(x == "above_horizon" ? 1 : x == "below_horizon" ? 0 : -1);'`);

// a change from anywhere but the entity itself -> move the entity (it publishes to HA and saves to NVS)
L.push('', 'esphome:', '  on_boot:', '    - priority: -100', '      then:', '        - lambda: |-',
  '            fw::dev::observe([](const char *k, const char *v, fw::dev::From from) {',
  '              if (from == fw::dev::HA) return;  // came from the entity: it has it already');
for (const s of sel) L.push(`              if (!strcmp(k, ${q(s.id)})) { auto c = id(${ent(s).id}).make_call(); c.set_option(fw::dev::option_label(k, v)); c.perform(); return; }`);
for (const s of sw) L.push(`              if (!strcmp(k, ${q(s.id)})) { if (!strcmp(v, "true")) id(${ent(s).id}).turn_on(); else id(${ent(s).id}).turn_off(); return; }`);
for (const s of nm) L.push(`              if (!strcmp(k, ${q(s.id)})) { auto c = id(${ent(s).id}).make_call(); c.set_value(atof(v)); c.perform(); return; }`);
L.push('            });', '');
const text = L.join('\n');
if (!existsSync(out) || readFileSync(out, 'utf8') !== text) writeFileSync(out, text);
